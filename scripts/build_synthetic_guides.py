def main():
    tokenizer = load_tokenizer()
    folder = ROOT / "fixtures/rag/guides"
    folder.mkdir(parents=True, exist_ok=True)
    catalog, counts = [], []
    for docid, case, title, paragraphs in TOPICS:
        text = "합성 학습 자료, 법률 자문 아님\n\n# " + title + "\n\n" + "\n\n".join(paragraphs)
        for extra in EXTRA:
            if len(tokenizer.encode(text)) >= 650:
                break
            text += "\n\n" + extra
        count = len(tokenizer.encode(text))
        if not 600 <= count <= 1200:
            raise ValueError(f"{docid}: {count} tokens outside 600..1200")
        file = folder / (docid + ".md")
        file.write_text(text + "\n", encoding="utf-8")
        catalog.append({"documentId": docid, "caseType": case, "title": title,
                        "sourceVersion": "synthetic-1", "file": file.relative_to(ROOT).as_posix()})
        counts.append({"documentId": docid, "caseType": case, "tokens": count})
    (folder.parent / "guides.json").write_text(json.dumps(catalog, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    print(json.dumps(counts, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
